// Sender classes returned by SenderClass.
const (
	ClassHuman         = "human"         // written by a person to a person
	ClassTransactional = "transactional" // machine-generated, but for this recipient specifically
	ClassBulk          = "bulk"          // marketing or newsletter sent to a list
	ClassList          = "list"          // relayed by a mailing list
	ClassAutomated     = "automated"     // system notification, bounce, or auto-reply
	ClassUnknown       = "unknown"       // not enough signal to decide
)

// HumanSignal is one piece of evidence for or against a message having been
// typed by a person.
type HumanSignal struct {
	Name    string  // stable identifier
	Weight  float64 // positive favours human, negative favours automated
	Present bool
	Detail  string
}

// HumanAssessment is the full result of human-versus-machine analysis.
type HumanAssessment struct {
	// Score runs from 0 (certainly machine-generated) to 100 (almost
	// certainly typed by a person).
	Score float64
	Class string
	// Signals lists every signal that fired, strongest evidence first.
	Signals []HumanSignal
	// Reasons is a human-readable summary of the firing signals.
	Reasons []string
}

